#!/usr/bin/env python3
"""Phase 5 — write the human-facing verification outputs from final-verdicts.jsonl
(+ Phase-4 validation if present):
  review/VERIFICATION-LEDGER.md  — every data-verifiable claim, its final status, basis, evidence
  review/FAILURES.md             — the confirmed FAIL claims with observed-vs-claimed and a fix
A FAIL is 'confirmed' only if Phase-4 validation exists and >=2 validators 'confirm' (or no Phase-4
run yet -> marked PROVISIONAL). Read-only w.r.t. thesis text."""
import json, glob, collections, os
import os
REV="/home/gio/tese/review"
_src=f"{REV}/final-verdicts.v2.jsonl" if os.path.exists(f"{REV}/final-verdicts.v2.jsonl") else f"{REV}/final-verdicts.jsonl"
FINAL=[json.loads(l) for l in open(_src) if l.strip()]

def load_p4():
    d=collections.defaultdict(list)
    for f in glob.glob(f"{REV}/reports/validation/*/p4.*.jsonl"):
        try: r=json.load(open(f)); d[r["claim_id"]].append(r)
        except: pass
    return d
P4=load_p4()

def evidence_for(cid):
    obs=[]
    # opus arbitration first (authoritative), then adjudicators, then phase-2
    af=f"{REV}/reports/arbitration/verdicts/{cid}.json"
    if os.path.exists(af):
        try:
            a=json.load(open(af))
            obs.append(("opus-arbiter",a.get("verdict"),a.get("observed"),a.get("fix"),a.get("severity")))
        except: pass
    for f in glob.glob(f"{REV}/reports/adjudication/*/p3.{cid}.jsonl")+glob.glob(f"{REV}/reports/*/p2.{cid}.*.jsonl"):
        try:
            r=json.load(open(f)); raw=r.get("raw") or {}
            if raw.get("observed"): obs.append((r["model"],r.get("verdict"),raw.get("observed"),raw.get("fix"),raw.get("severity")))
        except: pass
    return obs

def fail_status(cid):
    v=P4.get(cid,[])
    if not v: return "PROVISIONAL", 0, 0
    conf=sum(1 for r in v if r.get("decision")=="confirm")
    over=sum(1 for r in v if r.get("decision")=="overturn")
    if conf>=2: return "CONFIRMED", conf, over
    if over>=1 and conf<2: return "OVERTURNED", conf, over
    return "SPLIT", conf, over

tally=collections.Counter(r["status"] for r in FINAL)
bychap=collections.defaultdict(lambda: collections.Counter())
for r in FINAL: bychap[r["chapter"]][r["status"]]+=1

# ---- VERIFICATION-LEDGER.md ----
L=[f"# Verification Ledger — {len(FINAL)} data-verifiable claims\n",
   "Generated by the multi-agent verification pipeline (Phase 1 extract -> Phase 2 CONFIRM/REFUTE "
   "-> Phase 3 cross-family adjudication -> Phase 4 validation). Every verdict is grounded in a "
   "`db_query` against the provenance DB (read-only). Status legend: PASS / FAIL / UNVERIFIABLE / "
   "PASS-UNVER (supported where checkable, else no backing) / SPLIT / NO-VERDICT.\n",
   "## Tally\n", "| status | n |","|---|---|"]
for s,n in tally.most_common(): L.append(f"| {s} | {n} |")
L.append("\n## By chapter\n")
L.append("| chapter | PASS | FAIL | UNVER | PASS-UNVER | SPLIT | NO-VERDICT |"); L.append("|---|---|---|---|---|---|---|")
for ch in sorted(bychap):
    c=bychap[ch]; L.append(f"| {ch} | {c['PASS']} | {c['FAIL']} | {c['UNVERIFIABLE']} | {c['PASS-UNVER']} | {c['SPLIT']} | {c['NO-VERDICT']} |")
L.append("\n## Claims\n")
for r in sorted(FINAL, key=lambda x:(x["chapter"],x["claim_id"])):
    L.append(f"### `{r['claim_id']}` [{r['status']}] — {r['chapter']}")
    L.append(f"- **claim**: {r['claim_text']}")
    L.append(f"- **anchor**: \"{r['anchor']}\"")
    L.append(f"- **final verdict**: {r['verdict']} (basis: {r['basis']}; phase2={r['phase2_verdicts']}; adj={r['adjudicator_verdicts']})")
    if r["status"]=="FAIL":
        st,conf,over=fail_status(r["claim_id"]); L.append(f"- **validation**: {st} (confirm={conf}, overturn={over})")
    L.append("")
open(f"{REV}/VERIFICATION-LEDGER.md","w").write("\n".join(L))

# ---- FAILURES.md ----
F=["# Failures — claims the data does not support at the stated strength\n",
   "Each entry is a claim adjudicated FAIL (contradicted / overclaimed / inconsistent), with the "
   "observed DB value vs the text value and a proposed fix. `validation` shows the cross-family "
   "Phase-4 result.\n"]
fails=[r for r in FINAL if r["status"]=="FAIL"]
fails.sort(key=lambda r: {"blocking":0,"major":1,"minor":2}.get(
    next((s for *_,s in evidence_for(r["claim_id"]) if s), "minor"),2))
for r in fails:
    st,conf,over=fail_status(r["claim_id"])
    F.append(f"## `{r['claim_id']}` — {r['chapter']} — {r['verdict'].upper()} [validation: {st}]")
    F.append(f"- **claim**: {r['claim_text']}")
    F.append(f"- **anchor**: \"{r['anchor']}\"")
    F.append(f"- **expected backing**: {r.get('expected_backing')}")
    ev=evidence_for(r["claim_id"])
    for model,verdict,obs,fix,sev in ev[:4]:
        F.append(f"  - [{model}/{verdict}/{sev}] observed: {obs}" + (f" | fix: {fix}" if fix else ""))
    F.append("")
open(f"{REV}/FAILURES.md","w").write("\n".join(F))
print(f"wrote VERIFICATION-LEDGER.md ({len(FINAL)} claims) and FAILURES.md ({len(fails)} failures)")
print("tally:", dict(tally))
