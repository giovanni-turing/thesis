#!/bin/bash
# §8.8-1 independent reproduction runner, v2 (D50/D51/D53 closure).
#
# Reproduces THREE manuscript headline results from a CLEAN CHECKOUT (a
# detached git worktree of HEAD), using tracked files only — including the six
# TRACKED .jsonl.zst replay archives, inflated inside the checkout:
#
#   H1  0.623x — p90 forecast arm vs deployable static worker-time.
#       Locus: tex/closedloop.tex (frontier) + tex/conclusion.tex.
#       Predicate: 313-cell recomputation from raw tracked outputs; the
#       aggregate worker-s ratio rounds to 0.623.
#   H2  1.042x — cheapest all-passing warm-floor member (shipped mechanics).
#       Locus: tex/conclusion.tex + tex/closedloop.tex.
#       Predicate: from the same recomputation, over ALL warm_floor_* arms
#       (incl. the calibrated core M4), the min-cost member passing every
#       evaluation window AND aggregate is warm_floor_M6 at 1.042x static.
#   H3  1122/1143 ms — composed request-linked calm-day e2e p99, forecast vs
#       reactive. Locus: tex/closedloop.tex sec:cl-ledger-joint.
#       Predicate: composed_fill_joined.json regenerated BYTE-IDENTICAL to
#       the committed object; serialized decimals pinned exactly at
#       1122.2/1143.5 (printed 1122/1143 = nearest integers of the
#       pre-serialization full precision; see repro_predicates.headlines).
#
# Diagnostics (recorded, not headline results): worktree cleanliness, and the
# Stage-A tracked-only boundary — with all six .zst left deflated, exactly
# five pinned cells succeed field-equal to the committed artifact and exactly
# four pinned cells fail, each on its documented checkout-local input path
# (4/9 archive-dependent cells; six archive files).
#
# All pass/fail decisions live in verification/repro_predicates.py (negative
# probes: `repro_predicates.py --selftest`).
#
# Portability (D51): the repository is derived from this script's own
# location — run it from any clone. Environment knobs:
#   REPRO_PY       python with numpy+pandas (default: <repo>/eda/.venv if
#                  present, else python3; verification/repro_requirements.txt
#                  pins a minimal env that needs no GPU wheel)
#   REPRO_SCRATCH  scratch root; a unique owned run directory is created
#                  beneath it (default: mktemp -d under $TMPDIR)
#   REPRO_REPORT   report destination (default: <run dir>/report.md; published
#                  atomically, publication failure is fatal).
# No live-tree DATA INPUTS are read: every input resolves inside the worktree.
# Writes outside the run directory are limited to the source repository's
# .git/worktrees admin area (worktree add/remove) and, when REPRO_REPORT
# says so, the report destination.
set -u
SELF=$(cd "$(dirname "$0")" && pwd)
TESE=$(cd "$SELF/.." && pwd)
if [ -n "${REPRO_PY:-}" ]; then PY=$REPRO_PY
elif [ -x "$TESE/eda/.venv/bin/python" ]; then PY=$TESE/eda/.venv/bin/python
else PY=$(command -v python3); fi
# D51 round 2: a UNIQUE OWNED run directory is created beneath any scratch
# override; cleanup removes only what this process created, and a failed
# mktemp aborts instead of running in an unowned location.
RUN=$(mktemp -d "${REPRO_SCRATCH:-${TMPDIR:-/tmp}}/repro881.XXXXXX") \
  || { echo "FATAL: cannot create run directory" >&2; exit 1; }
# D54: the default report lives OUTSIDE the run directory removed at EXIT, so
# a successful default run's advertised report survives cleanup.
if [ -n "${REPRO_REPORT:-}" ]; then REPORT=$REPRO_REPORT
else
  REPORT=$(mktemp "${REPRO_SCRATCH:-${TMPDIR:-/tmp}}/repro881_report.XXXXXX.md") \
    || { echo "FATAL: cannot create report file" >&2; rm -rf "$RUN"; exit 1; }
fi
W=$RUN/checkout

cleanup() {
  git -C "$TESE" worktree remove --force "$W" >/dev/null 2>&1
  rm -rf "$RUN"
}
# D54: no-argument handlers (no arithmetic, no positional refs), so the trap
# body cannot mis-parse regardless of what the shell was executing when the
# signal arrived; each disables all traps, cleans, and exits 128+signal.
on_int()  { trap - EXIT INT TERM; cleanup; exit 130; }
on_term() { trap - EXIT INT TERM; cleanup; exit 143; }
trap on_int INT
trap on_term TERM
trap cleanup EXIT
# Test-only hook (repro_signal_test.sh): REPRO_PAUSE_AT=tools|worktree inserts
# a 5 s pause at that phase so signal delivery is deterministic.
pause_at() { [ "${REPRO_PAUSE_AT:-}" = "$1" ] && sleep 5; return 0; }

pass=0; fail=0
R=""
say() { echo "$1"; R+="$1"$'\n'; }
ok()  { pass=$((pass+1)); say "PASS  $1"; }
bad() { fail=$((fail+1)); say "FAIL  $1"; }
publish() {
  if printf '%s' "$R" > "$REPORT.tmp.$$" && mv "$REPORT.tmp.$$" "$REPORT"; then
    echo "report: $REPORT"
  else
    echo "FATAL: report publication to $REPORT failed" >&2
    rm -f "$REPORT.tmp.$$"
    exit 1
  fi
}

HEAD_SHA=$(git -C "$TESE" rev-parse HEAD)
pause_at tools
PYV=$("$PY" -c 'import sys, numpy, pandas; print(f"python {sys.version.split()[0]}, numpy {numpy.__version__}, pandas {pandas.__version__}")' 2>/dev/null) || PYV="PYTHON ENV UNUSABLE"
ZV=$(zstd --version 2>&1 | sed 's/\*\*\* //;s/, by.*//' | head -1)
GV=$(git --version)
say "# Clean-checkout reproduction of three headline results (§8.8-1, runner v2)"
say ""
say "repo: $TESE"
say "HEAD: $HEAD_SHA  ($(date -u +%Y-%m-%dT%H:%M:%SZ))"
say "tools: $PYV; $ZV; $GV"
say ""

# ---- fresh detached worktree (unique scratch; trap-cleaned) ----
pause_at worktree
if git -C "$TESE" worktree add --detach "$W" HEAD >/dev/null 2>&1 \
   && [ "$(git -C "$W" status --porcelain | wc -l)" -eq 0 ]; then
  ok "diagnostic: clean detached worktree at HEAD"
else
  bad "worktree creation not clean"; publish; exit 1
fi
# D51 round 2: pass/fail predicates come from the DETACHED CHECKOUT, so a
# dirty outer predicate cannot decide a report labeled with a clean HEAD; the
# (necessarily outer) invoking runner is hash-compared against the HEAD copy.
export PRED_DIR=$W/verification
if [ "$(sha256sum "$SELF/repro_clean_checkout.sh" | cut -d' ' -f1)" = \
     "$(sha256sum "$W/verification/repro_clean_checkout.sh" | cut -d' ' -f1)" ]; then
  say "runner: byte-identical to the HEAD copy"
else
  say "runner: WARNING -- invoking runner differs from the HEAD copy; this report reflects the invoking runner"
fi
COMMITTED=$W/simulation/results/composed_fill/composed_fill_joined.json

# ---- H1 + H2: frontier 313-cell recomputation ----
say ""
say "## H1 (0.623x) + H2 (1.042x) — comparator frontier recomputation"
FR=$W/simulation/results/comparator_frontier
(cd "$FR" && TESE_ROOT=$W "$PY" build_frontier_summary.py --jobs 8 \
   >"$RUN/frontier_build.log" 2>&1)
frc=$?
VERDICT=$(grep -E "^cells=" "$RUN/frontier_build.log" | tail -1)
say "verdict: ${VERDICT:-<none>}  rc=$frc"
if "$PY" - "$frc" "$VERDICT" <<'PYEOF'
import sys; sys.path.insert(0, __import__("os").environ["PRED_DIR"])
from repro_predicates import frontier_verdict_ok
sys.exit(0 if frontier_verdict_ok(int(sys.argv[1]), sys.argv[2]) else 1)
PYEOF
then
  ok "frontier: exact verdict (cells=313, zero missing/mismatched stats, calib-selection/calib-table/summary-link OK). Scope: the builder independently recomputes all 313 cells and confirms the LINKED summary fields; whole-summary byte identity is established by the delivery gate's make_frontier_report comparison, not here"
else
  bad "frontier recomputation verdict (see $RUN/frontier_build.log)"
fi

# ---- H3 + Stage B: composed join from tracked .zst, byte-identity ----
say ""
say "## H3 (1122/1143 ms) — composed nine-cell join from tracked archives"
ZOK=1
for f in defense/anim/data/a2_runs/steady24h_forecast_L30.jsonl \
         defense/anim/data/a2_runs/steady24h_reactive_L30.jsonl \
         defense/anim/data/a13_runs/ft_static_C8.jsonl \
         defense/anim/data/a13_runs/ft_llm_static.requests.jsonl \
         defense/anim/data/a13_runs/ft_reactive_L30.jsonl \
         defense/anim/data/a13_runs/ft_llm_reactive.requests.jsonl; do
  zstd -d -q -f "$W/$f.zst" -o "$W/$f" || { ZOK=0; bad "inflating $f.zst"; }
done
rm -f "$RUN/composed_B.json" || { bad "removal of composed_B.json failed"; publish; exit 1; }
if [ -e "$RUN/composed_B.json" ] || [ -L "$RUN/composed_B.json" ]; then
  bad "stale composed_B.json residue (incl symlink) after removal"; publish; exit 1
fi
TESE_ROOT=$W "$PY" "$W/simulation/composed_fill_join.py" \
  --out "$RUN/composed_B.json" >"$RUN/composed_B.log" 2>&1
brc=$?
if [ "$ZOK" -eq 1 ] && [ $brc -eq 0 ] \
   && cmp -s "$RUN/composed_B.json" "$COMMITTED"; then
  ok "composed artifact regenerated BYTE-IDENTICAL to the committed object (rc=0)"
else
  bad "composed regeneration or byte-identity (rc=$brc)"
fi

# ---- The three headline predicates ----
say ""
say "## Headline predicates (recomputed artifacts only)"
HL=$("$PY" - "$FR/frontier_summary_cells.json" "$RUN/composed_B.json" <<'PYEOF'
import json, os, sys
sys.path.insert(0, os.environ["PRED_DIR"])
from repro_predicates import headlines, headlines_ok
h = headlines(sys.argv[1], sys.argv[2])
for k in ("H1", "H2", "H3"):
    e = h[k]
    print(f"{k}: {e['claim']}  [locus: {e['locus']}]  recomputed={e['value']}"
          f" expected={e['expect']}" + (f" member={e['member']}" if k == "H2" else ""))
print("HEADLINES:", "OK" if headlines_ok(h) else "BAD")
PYEOF
)
say "$HL"
if echo "$HL" | grep -q "^HEADLINES: OK$"; then
  ok "all three headline predicates hold on the recomputed artifacts"
else
  bad "headline predicate failure"
fi

# ---- Diagnostic: archive manifest verifies from tracked .zst alone ----
say ""
say "## Diagnostic — replay-archive manifest (tracked archives only)"
if (cd "$W" && "$PY" verification/make_replay_archive_manifest.py --verify \
      >"$RUN/manifest_verify.log" 2>&1); then
  ok "manifest --verify inside the clean checkout: recomputed-from-stream fields equal the tracked manifest"
else
  bad "manifest --verify in clean checkout (see $RUN/manifest_verify.log)"
fi

# ---- Diagnostic: Stage-A tracked-only boundary (archives deflated) ----
say ""
say "## Diagnostic — tracked-only boundary (all six .zst deflated)"
for f in "$W"/defense/anim/data/a2_runs/*.jsonl "$W"/defense/anim/data/a13_runs/*.jsonl; do
  [ -e "$f" ] && rm -f "$f"
done
rm -f "$RUN/composed_A.json" || { bad "removal of composed_A.json failed"; publish; exit 1; }
if [ -e "$RUN/composed_A.json" ] || [ -L "$RUN/composed_A.json" ]; then
  bad "stale composed_A.json residue (incl symlink; join would PRELOAD it)"; publish; exit 1
fi
TESE_ROOT=$W "$PY" "$W/simulation/composed_fill_join.py" \
  --out "$RUN/composed_A.json" >"$RUN/composed_A.log" 2>&1
arc=$?
AV=$("$PY" - "$arc" "$RUN/composed_A.json" "$COMMITTED" "$W" <<'PYEOF'
import json, os, sys
sys.path.insert(0, os.environ["PRED_DIR"])
from repro_predicates import stage_a_ok
print(stage_a_ok(int(sys.argv[1]), json.load(open(sys.argv[2])),
                 json.load(open(sys.argv[3])), sys.argv[4]))
PYEOF
)
say "boundary verdict: $AV"
if [ "$AV" = "OK" ]; then
  ok "boundary exact: the five pinned tracked-only cells succeed field-equal to the committed artifact; the four pinned archive-dependent cells (4/9) each fail on their documented checkout-local input"
else
  bad "tracked-only boundary not as documented"
fi

say ""
say "## Result"
say ""
say "$pass passed, $fail failed"
publish
[ $fail -eq 0 ]
